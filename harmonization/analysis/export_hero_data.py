"""Export the real numbers shown in the landing page preview (web/components/HeroHarmonizationPreview.tsx).

    python3 -I analysis/export_hero_data.py harmonized_hotspots.sqlite ../web/lib/hero-data.ts

All of Mexico, from the harmonized archive (csv_to_sqlite.py output):
  harmonized[y][m] = rows with in_calendar = 1           (the consistent series)
  raw[y][m]        = non-low S-NPP rows (2012-) or non-low Aqua rows (before), i.e. what you get without harmonizing
  bars per year    = non-low Aqua rows, non-low S-NPP rows, in_calendar = 1 rows
"""
import json, sqlite3, sys

HEAT_YEARS = list(range(2019, 2026))
BAR_YEARS = [2004, 2008, 2012, 2016, 2020, 2024]

db, out = sys.argv[1], sys.argv[2]
con = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
q = """SELECT substr(ym, 1, 4) y, CAST(substr(ym, 6, 2) AS INTEGER) m,
          SUM(in_calendar = '1'),
          SUM(satellite = 'Aqua' AND confidence != 'l'),
          SUM(satellite = 'SNPP' AND confidence != 'l')
       FROM hotspots GROUP BY ym"""
cal, aqua, snpp = {}, {}, {}
for y, m, c, a, s in con.execute(q):
    cal[(int(y), m)], aqua[(int(y), m)], snpp[(int(y), m)] = c, a, s
max_date = con.execute("SELECT value FROM meta WHERE key = 'max_date'").fetchone()[0]

harm = [[cal.get((y, m), 0) for m in range(1, 13)] for y in HEAT_YEARS]
raw = [[snpp.get((y, m), 0) if y >= 2012 else aqua.get((y, m), 0) for m in range(1, 13)] for y in HEAT_YEARS]
bars = [{"year": str(y),
         "rawModis": sum(aqua.get((y, m), 0) for m in range(1, 13)),
         "rawViirs": (sum(snpp.get((y, m), 0) for m in range(1, 13)) or None) if y >= 2012 else None,
         "harmonized": sum(cal.get((y, m), 0) for m in range(1, 13))} for y in BAR_YEARS]
total_cal = con.execute("SELECT SUM(n_calendar) FROM monthly").fetchone()[0]
# seam check: yearly S-NPP series cells / Aqua non-low pixels over 2012-2019 (1.0 = no step at the sensor change)
ratios = [r for (r,) in con.execute(
    "SELECT 1.0 * SUM(n_snpp) / SUM(n_aqua) FROM monthly WHERE ym BETWEEN '2012' AND '2019-12' GROUP BY substr(ym, 1, 4)")]

ts = f"""// GENERATED by harmonization/analysis/export_hero_data.py from the national harmonized archive
// (harmonized_hotspots.sqlite, data through {max_date}). Real NASA FIRMS counts for all of Mexico — do not edit by hand.

export const HERO_SOURCE = {json.dumps(f"NASA FIRMS harmonized archive · Mexico · data through {max_date}")};
export const HERO_TOTAL_SERIES = {total_cal};
/** Yearly S-NPP (in_calendar) / Aqua (non-low) ratio, 2012–2019: 1.0 = no step at the sensor change. */
export const HERO_SEAM_RATIO = {{ min: {min(ratios):.2f}, max: {max(ratios):.2f} }};
export const HERO_YEARS = {json.dumps(HEAT_YEARS)};
/** in_calendar = 1 detections per month (the harmonized series). */
export const HERO_HARMONIZED: number[][] = {json.dumps(harm)};
/** Non-low S-NPP detections per month (what VIIRS reports before harmonizing). */
export const HERO_RAW: number[][] = {json.dumps(raw)};
/** Yearly totals: non-low Aqua MODIS, non-low S-NPP VIIRS (from 2012-01-20), in_calendar = 1. */
export const HERO_BARS: {{ year: string; rawModis: number; rawViirs: number | null; harmonized: number }}[] = {json.dumps(bars)};
"""
open(out, "w", encoding="utf-8").write(ts)
print(f"wrote {out}: series total {total_cal:,}; bars {bars}")
